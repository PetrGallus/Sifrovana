import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";

const contentFiles = [
  "../content/route-checkpoint-drafts/medlanky.json",
  "../content/route-checkpoint-drafts/reckovice.json",
  "../content/route-checkpoint-drafts/cerna-pole-a-vanoce.json",
];

const [cms, generator, migration, ...documents] = await Promise.all([
  readFile(new URL("../app/route-cms.tsx", import.meta.url), "utf8"),
  readFile(new URL("../scripts/generate-route-draft-migration.mjs", import.meta.url), "utf8"),
  readFile(new URL("../supabase/migrations/20261106131056_seed_northern_route_checkpoint_drafts.sql", import.meta.url), "utf8"),
  ...contentFiles.map(async (file) => JSON.parse(await readFile(new URL(file, import.meta.url), "utf8"))),
]);

const routes = documents.flatMap((document) => document.routes);
const checkpoints = routes.flatMap((route) => route.checkpoints.map((checkpoint) => ({ ...checkpoint, route_id: route.route_id })));

test("authors exactly ten route briefs and 73 checkpoint drafts", () => {
  assert.equal(routes.length, 10);
  assert.equal(checkpoints.length, 73);
  assert.equal(new Set(routes.map((route) => route.route_id)).size, 10);
  assert.equal(new Set(checkpoints.map((checkpoint) => `${checkpoint.route_id}-${checkpoint.slug}`)).size, 73);
  for (const route of routes) {
    assert.deepEqual(route.checkpoints.map((checkpoint) => checkpoint.position), Array.from({ length: route.checkpoints.length }, (_, index) => index + 1));
  }
});

test("keeps every authored coordinate and answer explicitly unverified", () => {
  for (const checkpoint of checkpoints) {
    assert.ok(checkpoint.internal_notes.startsWith("ORIENTAČNÍ SOUŘADNICE — TERÉNNĚ OVĚŘIT."));
    assert.ok(checkpoint.candidate_answers.length > 0);
    assert.equal(Object.hasOwn(checkpoint, "accepted_answers"), false);
    assert.ok(Number.isFinite(checkpoint.latitude));
    assert.ok(Number.isFinite(checkpoint.longitude));
  }
});

test("generates inactive CMS rows without promoting candidate answers", () => {
  assert.match(generator, /accepted_answers, hint_1, hint_2, fallback_prompt, fallback_answers/);
  assert.match(generator, /array\[\]::text\[\]/);
  assert.match(generator, /seed\.internal_notes.*Kandidátní odpovědi/s);
  assert.match(generator, /false\nfrom route_checkpoint_draft_seed/);
  assert.match(generator, /case when seed\.position = 1 then 0 else null end/);
  assert.match(generator, /on conflict \(id\) do nothing/);
  assert.match(generator, /source override requires both source_url and source_title/);
  assert.match(migration, /Generated by scripts\/generate-route-draft-migration\.mjs/);
  assert.match(migration, /on conflict \(id\) do nothing/);
  assert.match(migration, /on conflict \(route_id, coalesce\(checkpoint_id, ''\), url\) do nothing/);
});

