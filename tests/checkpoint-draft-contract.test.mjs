test("enforces publication invariants in the database", () => {
  assert.match(generator, /new\.commercial_readiness <> 'ready'/);
  assert.match(generator, /new\.last_field_check is null or new\.last_field_check > current_date/);
  assert.match(generator, /new\.stroller_status = 'unknown'/);
  assert.match(generator, /new\.preschool_status = 'unknown'/);
  assert.match(generator, /create constraint trigger cms_routes_enforce_publication_invariant/);
  assert.match(generator, /create trigger enforce_cms_publication_source_gate/);
  assert.match(generator, /checkpoint\.is_active/);
  assert.match(generator, /min\(checkpoint\.position\) = 1[\s\S]*max\(checkpoint\.position\) = count\(\*\)[\s\S]*count\(distinct checkpoint\.position\) = count\(\*\)/);
  assert.match(generator, /checkpoint\.position = 1 and coalesce\(checkpoint\.distance_from_previous_km, -1\) <> 0/);
  assert.match(generator, /checkpoint\.position > 1 and coalesce\(checkpoint\.distance_from_previous_km, 0\) <= 0/);
  assert.match(generator, /\(route_record\.availability = 'seasonal'\) <> \(route_record\.seasonality = 'seasonal'\)/);
  assert.match(generator, /route_record\.available_from > route_record\.available_to/);
  assert.ok(generator.includes("source.url ~ '^https://[^/[:space:]]+([/?#]|$)'"));
  assert.match(generator, /source\.verified_at is not null/);
  assert.match(generator, /source\.verified_at <= current_date/);
});

test("builds snapshots only from publication-eligible records", () => {
  const publishFunction = generator.match(/create or replace function public\.publish_cms_route\(p_route_id text\)[\s\S]*?\n\$publish\$;/)?.[0];
  assert.ok(publishFunction, "publish_cms_route definition is missing");
  assert.match(publishFunction, /from public\.cms_checkpoints c where c\.route_id = r\.id and c\.is_active/);
  assert.match(publishFunction, /from public\.cms_sources s[\s\S]*s\.checkpoint_id is null or exists \([\s\S]*c\.is_active/);
  assert.match(publishFunction, /from public\.cms_media m[\s\S]*m\.checkpoint_id is null or exists \([\s\S]*c\.is_active/);
  assert.ok(publishFunction.includes("s.url ~ '^https://[^/[:space:]]+([/?#]|$)'"));
  assert.match(publishFunction, /s\.verified_at <= current_date/);
});
